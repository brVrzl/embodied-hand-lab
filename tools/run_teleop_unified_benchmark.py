#!/usr/bin/env python3
"""Generate the offline-only unified PWL/Ruckig/B/C benchmark JSON."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess

from teleop_rearchitecture.unified_evaluator import (
    ALL_BACKENDS,
    evaluate_unified_fixture,
    load_accepted_joint_targets,
    render_benchmark_markdown_rows,
)


DEFAULT_FIXTURES = (
    Path("docs/history/incidents/quest_jaka_20260722_23/measurements/jaka_edg_sim_initial_accepted_targets_20260722.jsonl"),
    Path("docs/history/incidents/quest_jaka_20260722_23/measurements/jaka_edg_failed_run_accepted_targets_20260722.jsonl"),
)


def _git_value(*arguments: str) -> str:
    return subprocess.run(
        ("git", *arguments), check=True, text=True, capture_output=True
    ).stdout.strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture", action="append", type=Path, dest="fixtures")
    parser.add_argument("--model", type=Path, default=Path("data/sim_assets/jaka_rh56.xml"))
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--markdown-output", type=Path)
    parser.add_argument(
        "--cpp-library",
        type=Path,
        help="explicit built offline C++ reference library; adds candidate_c_cpp_reference",
    )
    args = parser.parse_args()
    commit = _git_value("rev-parse", "HEAD")
    dirty = bool(_git_value("status", "--porcelain"))
    reports = [
        evaluate_unified_fixture(
            load_accepted_joint_targets(path),
            model_path=args.model,
            repository_commit=commit,
            working_tree_dirty=dirty,
            backends=(
                (*ALL_BACKENDS, "candidate_c_cpp_reference")
                if args.cpp_library is not None
                else ALL_BACKENDS
            ),
            cpp_library_path=args.cpp_library,
        )
        for path in (args.fixtures or DEFAULT_FIXTURES)
    ]
    payload = {
        "schema_version": "teleop_unified_benchmark_set.v1",
        "repository_commit": commit,
        "working_tree_dirty": dirty,
        "reports": reports,
        "generated_markdown_rows": [
            row for report in reports for row in render_benchmark_markdown_rows(report)
        ],
        "physical_connections": False,
        "physical_commands": False,
        "jaka_sdk_loaded": False,
        "rh56_commands": 0,
    }
    json.dumps(payload, allow_nan=False)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if args.markdown_output is not None:
        lines = [
            "<!-- Generated by tools/run_teleop_unified_benchmark.py; do not hand edit. -->",
            "",
            "| Fixture | Backend | causal position RMS mm | causal orientation RMS mrad | interpolated position RMS mm | interpolated orientation RMS mrad |",
            "| --- | --- | ---: | ---: | ---: | ---: |",
            *payload["generated_markdown_rows"],
            "",
        ]
        args.markdown_output.parent.mkdir(parents=True, exist_ok=True)
        args.markdown_output.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
